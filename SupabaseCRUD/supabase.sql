-- Catálogo de productos para SupabaseCRUD
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  producto text not null check (char_length(trim(producto)) between 1 and 100),
  descripcion text not null default '' check (char_length(descripcion) <= 500),
  precio numeric(10, 2) not null check (precio >= 0),
  created_at timestamptz not null default now()
);

alter table public.productos enable row level security;

drop policy if exists "Lectura pública de productos" on public.productos;
drop policy if exists "Alta pública de productos" on public.productos;
drop policy if exists "Edición pública de productos" on public.productos;
drop policy if exists "Eliminación pública de productos" on public.productos;

-- Políticas abiertas para la práctica académica sin autenticación.
-- En producción, restringe estas operaciones a usuarios autenticados.
create policy "Lectura pública de productos" on public.productos
  for select to anon, authenticated using (true);
create policy "Alta pública de productos" on public.productos
  for insert to anon, authenticated with check (true);
create policy "Edición pública de productos" on public.productos
  for update to anon, authenticated using (true) with check (true);
create policy "Eliminación pública de productos" on public.productos
  for delete to anon, authenticated using (true);
